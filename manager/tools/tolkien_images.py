def _eleventy_one_cake():
    """Birthday cake with '111' iced on it."""
    rows = [list(r) for r in CAKE]
    for dy in range(5):
        for dx in (3, 5, 7):
            rows[6 + dy][dx] = "R"
    return ["".join(r) for r in rows]


def make_tolkien(key):
    _name, _title, background, rows, overrides = TOLKIEN[key]
    if rows is None:
        rows, overrides = _eleventy_one_cake(), {"R": (200, 20, 40)}
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), "%s sprite must be 12x12" % key
    img = gradient(*background)
    sprite(img, rows, {**LOTR_PALETTE, **overrides})
    return img


TOLKIEN_IMAGES = {"%s.png" % spec[0]: (lambda k=key: make_tolkien(k)) for key, spec in TOLKIEN.items()}
