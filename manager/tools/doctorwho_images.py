def _flux(img):
    """Two interleaved spiral arms, purple and orange."""
    cx, cy = EMBLEM_X + 5.5, EMBLEM_Y + 5.5
    for arm, color in ((0, (170, 70, 220)), (math.pi, (255, 150, 40))):
        pts = []
        for i in range(400):
            t = i * 0.03
            r = 0.4 + t * 0.55
            if r > 6:
                break
            a = t + arm
            pts.append((round(cx + r * math.cos(a)), round(cy + r * math.sin(a))))
        plot(img, pts, color)
    plot(img, [(round(cx), round(cy))], (255, 255, 255))


DRAWN = {"dw_flux": _flux}


def make_doctorwho(name):
    background, rows, overrides = SPRITES[name]
    img = gradient(*background)
    if rows is None:
        DRAWN[name](img)
    else:
        assert len(rows) == 12 and all(len(r) == 12 for r in rows), "%s sprite must be 12x12" % name
        sprite(img, rows, {**DW_PALETTE, **overrides})
    return img


DOCTORWHO_IMAGES = {"%s.png" % name: (lambda n=name: make_doctorwho(n)) for name in SPRITES}
