def make_science(name):
    background, rows, overrides = SPRITES[name]
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), "%s sprite must be 12x12" % name
    img = gradient(*background)
    sprite(img, rows, {**SCIENCE_PALETTE, **overrides})
    return img


SCIENCE_IMAGES = {"%s.png" % name: (lambda n=name: make_science(n)) for name in SPRITES}
