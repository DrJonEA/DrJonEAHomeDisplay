def make_dickens(name):
    background, rows, overrides = SPRITES[name]
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), "%s sprite must be 12x12" % name
    img = gradient(*background)
    sprite(img, rows, {**DICKENS_PALETTE, **overrides})
    return img


DICKENS_IMAGES = {"%s.png" % name: (lambda n=name: make_dickens(n)) for name in SPRITES}
